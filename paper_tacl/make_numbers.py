def mac(name: str, val: str) -> None:
    lines.append(rf"\newcommand{{\{name}}}{{{val}}}")


def pct(x: float, d: int = 1) -> str:
    return f"{100 * x:.{d}f}\\%"


def pp(x: float) -> str:
    return f"{100 * x:+.1f}".replace("-", "$-$")


def ci(lo: float, hi: float, unit: str = "pp") -> str:
    f = (lambda v: f"{100 * v:+.1f}") if unit == "pp" else (lambda v: f"{100 * v:.1f}")
    return f"[{f(lo)}, {f(hi)}]".replace("-", "$-$")


def pval(p: float) -> str:
    if p < 0.001:
        return f"{p:.1e}".replace("e-0", r"\times10^{-").replace("e-", r"\times10^{-") + "}"
    return f"{p:.3f}"


