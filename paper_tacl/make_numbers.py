"""Write paper_tacl/numbers_rev.tex from the revision's results JSON.

    python paper_tacl/make_numbers.py

Every number the TACL draft states that is not already in paper/numbers.tex
(the submitted study's macros, still generated by src/engine_b.py) comes from
here, so prose and results cannot drift apart. Missing inputs produce
\\PENDING{...} markers instead of numbers, which render in red.
"""
